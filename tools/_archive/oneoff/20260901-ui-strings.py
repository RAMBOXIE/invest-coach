def split_comments(s):
    """把注释切出来占位，替换完再贴回去。注释里的内部命名不该被改。"""
    holes = []

    def stash(m):
        holes.append(m.group(0))
        return f"\x00{len(holes) - 1}\x00"

    s = re.sub(r"/\*.*?\*/", stash, s, flags=re.S)
    s = re.sub(r"(?m)^[ \t]*//[^\n]*", stash, s)
    s = re.sub(r"<!--.*?-->", stash, s, flags=re.S)
    return s, holes


def restore(s, holes):
    return re.sub(r"\x00(\d+)\x00", lambda m: holes[int(m.group(1))], s)


def main():
    total = 0
    for f in FILES:
        s = f.read_text(encoding="utf-8")
        body, holes = split_comments(s)
        n = 0
        for old, new in REPL:
            c = body.count(old)
            if c:
                body = body.replace(old, new)
                n += c
        f.write_text(restore(body, holes), encoding="utf-8")
        print(f"  {f.name:16s} 替换 {n} 处")
        total += n
    print(f"合计 {total} 处")


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except AttributeError:
        pass
    main()
